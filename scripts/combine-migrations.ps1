<#
.SYNOPSIS
  Writes supabase\bvm_all_in_one.sql: every file in supabase\migrations, in
  name order, as one script to paste into the Supabase SQL Editor.

.DESCRIPTION
  Run it again after adding or changing a migration. The combined file is
  deliberately outside supabase\migrations, so the CLI (`supabase db push`)
  and supabase\tests\validate-local.ps1 never apply it twice.
#>
$ErrorActionPreference = 'Stop'
$repo = Split-Path -Parent $PSScriptRoot
$files = Get-ChildItem (Join-Path $repo 'supabase\migrations') -Filter '*.sql' | Sort-Object Name
$header = @(
    '-- ============================================================================='
    '-- BVM: complete database setup in one file.'
    '--'
    '-- Supabase dashboard > SQL Editor > New query > paste this whole file > Run.'
    '-- Safe to run again (every part is re-runnable), so it also upgrades a'
    '-- project that ran some of the separate migrations before.'
    '--'
    '-- GENERATED by scripts\combine-migrations.ps1 from supabase\migrations:'
) + ($files | ForEach-Object { "--   $($_.Name)" }) + @(
    '-- Do not edit here; edit the migration and regenerate.'
    '-- ============================================================================='
    ''
)
$parts = foreach ($f in $files) {
    "`n-- >>>>>>>>>> $($f.Name) >>>>>>>>>>`n"
    (Get-Content -Raw $f.FullName).Replace("`r`n", "`n").TrimEnd() + "`n"
}
$out = Join-Path $repo 'supabase\bvm_all_in_one.sql'
$text = ($header -join "`n") + ($parts -join '')
[System.IO.File]::WriteAllText($out, $text, (New-Object System.Text.UTF8Encoding($false)))
Write-Host ("Wrote {0} ({1:N0} KB, {2} migrations)" -f $out, ((Get-Item $out).Length / 1KB), $files.Count)
