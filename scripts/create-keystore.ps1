<#
.SYNOPSIS
  Creates the Android upload keystore for release builds.

.DESCRIPTION
  Generates .secrets\upload-keystore.jks (RSA 4096, valid ~27 years) with a
  random 32-character password and writes android\key.properties pointing at
  it. Both locations are git-ignored. Back up the .secrets folder somewhere
  safe and offline: with Google Play App Signing a lost upload key can be
  reset through Play support, but sideloaded users can only update with the
  same key.

  Refuses to overwrite an existing keystore unless -Force is given.
#>
[CmdletBinding()]
param(
    [string] $Alias = 'upload',
    [string] $DistinguishedName = 'CN=BVM, O=BVM',
    [switch] $Force
)

$ErrorActionPreference = 'Stop'
. (Join-Path $PSScriptRoot 'env.ps1')

$repo = Split-Path -Parent $PSScriptRoot
$secrets = Join-Path $repo '.secrets'
$keystore = Join-Path $secrets 'upload-keystore.jks'
$properties = Join-Path $repo 'android\key.properties'

if ((Test-Path $keystore) -and -not $Force) {
    if (-not (Test-Path $properties)) {
        throw "Keystore exists at $keystore but android\key.properties is missing. Restore it from your backup."
    }
    Write-Host "Keystore already exists: $keystore (use -Force to replace it)."
    return
}

New-Item -ItemType Directory -Force -Path $secrets | Out-Null

# 32 random characters from a CSPRNG (letters and digits only, so the value is
# safe in a .properties file and on the keytool command line).
$alphabet = [char[]]'ABCDEFGHJKLMNPQRSTUVWXYZabcdefghijkmnopqrstuvwxyz23456789'
$bytes = New-Object byte[] 64
[System.Security.Cryptography.RandomNumberGenerator]::Create().GetBytes($bytes)
$password = -join ($bytes[0..31] | ForEach-Object { $alphabet[$_ % $alphabet.Length] })

if (Test-Path $keystore) { Remove-Item -Force $keystore }
$keytool = Join-Path $env:JAVA_HOME 'bin\keytool.exe'
# keytool reports progress on stderr; keep that from aborting the script and
# judge success by the exit code.
$previous = $ErrorActionPreference
$ErrorActionPreference = 'Continue'
& $keytool -genkeypair `
    -keystore $keystore -storetype PKCS12 `
    -alias $Alias -keyalg RSA -keysize 4096 -validity 10000 `
    -storepass $password -keypass $password `
    -dname $DistinguishedName 2>&1 | Out-Null
$exit = $LASTEXITCODE
$ErrorActionPreference = $previous
if ($exit -ne 0 -or -not (Test-Path $keystore)) { throw "keytool failed (exit code $exit)" }

$storeFile = $keystore.Replace('\', '/')
@(
    '# Generated by scripts/create-keystore.ps1 - never commit this file.',
    "storeFile=$storeFile",
    "storePassword=$password",
    "keyAlias=$Alias",
    "keyPassword=$password"
) | Set-Content -Path $properties -Encoding ascii

Write-Host "Created $keystore"
Write-Host "Wrote   $properties"
Write-Host 'Back up the .secrets folder and android\key.properties offline.'
